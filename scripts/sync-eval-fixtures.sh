#!/usr/bin/env bash
# Build each eval case's scaffold.sh from its skill's shared fixture plus the case's setup.sh:
# evals/<skill>/_fixture/fixture.sh + evals/<skill>/<case>/setup.sh → evals/<skill>/<case>/scaffold.sh
# (scaffolds cannot read files outside their case).
# Usage: sync-eval-fixtures.sh [--check]   (--check: exit 1 if any scaffold.sh is out of date)
set -euo pipefail
cd "$(dirname "$0")/.."

shopt -s nullglob
stale=0
for setup in evals/*/*/setup.sh; do
  case_dir=$(dirname "$setup")
  fixture="$(dirname "$case_dir")/_fixture/fixture.sh"
  expected=$(printf '# Generated by scripts/sync-eval-fixtures.sh from %s + setup.sh. Do not edit.\n' "$fixture"; cat "$fixture"; echo; cat "$setup")
  if [ "${1:-}" = "--check" ]; then
    [ "$(cat "$case_dir/scaffold.sh" 2> /dev/null)" = "$expected" ] || {
      echo "✘ $case_dir/scaffold.sh is out of date: run scripts/sync-eval-fixtures.sh" >&2
      stale=1
    }
  else
    printf '%s\n' "$expected" > "$case_dir/scaffold.sh"
  fi
done
exit "$stale"
